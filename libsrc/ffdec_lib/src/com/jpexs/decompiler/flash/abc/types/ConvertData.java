package com.jpexs.decompiler.flash.abc.types;

import com.jpexs.decompiler.flash.abc.ABC;
import com.jpexs.decompiler.flash.abc.avm2.model.CallPropertyAVM2Item;
import com.jpexs.decompiler.flash.abc.avm2.model.FullMultinameAVM2Item;
import com.jpexs.decompiler.flash.abc.avm2.model.ThisAVM2Item;
import com.jpexs.decompiler.flash.abc.types.traits.Trait;
import com.jpexs.decompiler.flash.abc.types.traits.TraitMethodGetterSetter;
import com.jpexs.decompiler.flash.abc.types.traits.TraitSlotConst;
import com.jpexs.decompiler.flash.configuration.Configuration;
import com.jpexs.decompiler.graph.GraphTargetItem;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Data for conversion.
 *
 * @author JPEXS
 */
public class ConvertData {

    public int deobfuscationMode;

    public Map<TraitSlotConst, AssignedValue> assignedValues = new LinkedHashMap<>();

    public boolean thisHasDefaultToPrimitive;

    public boolean ignoreFrameScripts;
    
    public boolean ignoreAccessibility;

    /**
     * Instance methods whose complete behavior was restored as FLA parameters.
     * Only the FLA exporter supplies this set; ordinary script export keeps them.
     */
    public Set<MethodBody> ignoredInstanceMethods = Collections.emptySet();

    public boolean exportEmbed;

    public boolean exportEmbedFlaMode;

    public String assetsDir = "/_assets/";

    public ConvertData() {
        deobfuscationMode = Configuration.autoDeobfuscate.get() ? 1 : 0;
    }

    /**
     * Removes direct calls to parameter initializers regenerated by Flash.
     *
     * @param abc ABC
     * @param classIndex Owning class
     * @param items Top-level method statements
     */
    public void removeIgnoredMethodCalls(ABC abc, int classIndex, List<GraphTargetItem> items) {
        if (ignoredInstanceMethods.isEmpty() || classIndex < 0) {
            return;
        }
        Set<String> names = new LinkedHashSet<>();
        for (Trait trait : abc.instance_info.get(classIndex).instance_traits.traits) {
            if (trait instanceof TraitMethodGetterSetter
                    && ignoredInstanceMethods.contains(abc.findBody(((TraitMethodGetterSetter) trait).method_info))) {
                names.add(trait.getName(abc).getName(new LinkedHashSet<>(), abc, abc.constants, Collections.emptyList(), false, false));
            }
        }
        items.removeIf(item -> {
            if (!(item instanceof CallPropertyAVM2Item)) {
                return false;
            }
            CallPropertyAVM2Item call = (CallPropertyAVM2Item) item;
            return call.receiver instanceof ThisAVM2Item && call.arguments.isEmpty()
                    && call.propertyName instanceof FullMultinameAVM2Item
                    && names.contains(((FullMultinameAVM2Item) call.propertyName).resolvedMultinameName);
        });
    }
}
